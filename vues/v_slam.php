    <h1>SLAM</h1>
    <h3>Programme de la formation</h3>
    <p>La formation comprend des enseignements généraux tels que la culture générale, l'anglais, les mathématiques pour l'informatique et la culture économique, juridique et managériale. Elle se divise en trois blocs de compétences avec des savoirs associés.

    Le Bloc n°1 concerne la gestion des services informatiques, incluant la réponse aux incidents et le développement en ligne. Le Bloc n°2 porte sur la conception et le développement d'applications, en veillant à la maintenance et à la gestion des données. Le Bloc n°3 se concentre sur la cybersécurité, protégeant les données et les équipements contre les cyberattaques.

    La formation inclut aussi des ateliers professionnels et des options facultatives, avec un stage de 10 semaines durant les 2 années.</p>
    <h3>Accès à la formation</h3>
    <p>Le BTS SIO option SLAM est accessible avec un bac pro CIEL (cybersécurité, informatique et réseaux, électronique), un bac technologique (STMG ou STI2D) ou un bac général. Accès sur dossier, voire tests et/ou entretien.</p>
    <h3>Poursuite d'études</h3>
    <p>Licence mention informatique
    Licence mention informatique, mathématiques
    Licence pro mention métiers de l'informatique : applications web
    Licence pro mention métiers de l'informatique : conception, développement et test de logiciels
    Classe préparatoire ATS ingénierie industrielle</p>
