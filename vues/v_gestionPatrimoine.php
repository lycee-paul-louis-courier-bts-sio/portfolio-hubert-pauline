        <h1> Gestion du patrimoine</h1>

        <p>Les collaborateurs de Stock2Com font appel à des serveurs externes gérés par Gandi et utilisent des ordinateurs de bureau et portables fournis par leur société. Les stations de travail ne font que se servir de terminaux pour se connecter aux serveurs et d'instruments de codage. Stock2Com emploie l'outil de versionnage rdiff-backup pour faire le suivi des versions d'un projet et gérer les backups et restaurations de serveurs, cet outil enregistre chaque changement effectué sur un ou plusieurs fichiers.

Dans le domaine des applications, la société se sert de Capistrano, un outil open source généralement employé pour le déploiement d'applications Web, qui offre également la possibilité de sauvegarder des projets. Toutes leurs applications sont développées en utilisant le Framework Ruby on Rails, qui repose sur le langage Ruby.
</p>
