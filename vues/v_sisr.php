    <h1>SISR</h1>
    <h3>Programme de la formation</h3>
    <p>La formation comprend des enseignements généraux comme la culture générale, l'anglais, les mathématiques appliquées à l'informatique et la culture économique, juridique et managériale, ainsi que des enseignements professionnels organisés en trois blocs de compétences.

    Le bloc n°1 porte sur le support et la mise à disposition de services informatiques. Le bloc n°2 concerne l'administration des systèmes et des réseaux. Le bloc n°3 traite de la cybersécurité des services informatiques. Chaque bloc inclut des compétences spécifiques et des savoirs associés.

    La formation propose également des ateliers de professionnalisation et des enseignements facultatifs. Les élèves effectuent un stage de 10 semaines pendant les deux années de formation.</p>
    <h3>Accès à la formation</h3>
    <p>Le BTS SIO option SISR est accessible avec un bac pro CIEL (cybersécurité, informatique et réseaux, électronique), un bac technologique (STMG ou STI2D) ou un bac général. Accès sur dossier, voire tests et/ou entretien.</p>
    <h3>Poursuite d'études</h3>
    <p>Administrateur systèmes, réseaux et bases de données
    Chef de projet logiciel et réseau
    Licence mention informatique
    Licence pro mention métiers de l'informatique : administration et sécurité des systèmes et des réseaux
    Licence pro mention métiers de l'informatique : conduite de projets
    Licence pro mention métiers de l'informatique : systèmes d'information et gestion de données
    Licence pro mention métiers des réseaux informatiques et télécommunications
    Classe préparatoire ATS ingénierie industrielle
    Expert en informatique et système d'information (EPSI)</p>
